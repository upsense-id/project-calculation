    function $(selector, root) {
        return (root || document).querySelector(selector);
    }

    function $$(selector, root) {
        return Array.prototype.slice.call((root || document).querySelectorAll(selector));
    }

    function byId(id) {
        return document.getElementById(id);
    }

    function escapeHtml(value) {
        return String(value === null || value === undefined ? '' : value)
            .replace(/&/g, '&amp;')
            .replace(/</g, '&lt;')
            .replace(/>/g, '&gt;')
            .replace(/"/g, '&quot;')
            .replace(/'/g, '&#039;');
    }

    function formatRp(value) {
        var number = Number(value) || 0;
        try {
            return 'Rp ' + new Intl.NumberFormat('id-ID', { maximumFractionDigits: 0 }).format(Math.round(number));
        } catch (error) {
            return 'Rp ' + Math.round(number).toLocaleString('id-ID');
        }
    }

    function formatDecimal(value, digits) {
        var number = Number(value) || 0;
        try {
            return new Intl.NumberFormat('id-ID', {
                minimumFractionDigits: 0,
                maximumFractionDigits: typeof digits === 'number' ? digits : 2
            }).format(number);
        } catch (error) {
            return String(number);
        }
    }

    function plainNumber(value) {
        var number = Number(value) || 0;
        return String(Math.round(number * 100) / 100);
    }

    function formatDays(value) {
        var number = Number(value) || 0;
        var label = Math.abs(number - 1) < 0.00001 ? 'Day' : 'Days';
        return formatDecimal(number, 2) + ' ' + label;
    }

    function todayISO() {
        var date = new Date();
        var local = new Date(date.getTime() - date.getTimezoneOffset() * 60000);
        return local.toISOString().slice(0, 10);
    }

    function formatDateId(value) {
        if (!value || !/^\d{4}-\d{2}-\d{2}$/.test(value)) {
            return value || '-';
        }
        var parts = value.split('-');
        return parts[2] + '/' + parts[1] + '/' + parts[0];
    }

    function defaultRef() {
        var settings = state.settings || DEFAULT_SETTINGS;
        var prefix = String(settings.ref_prefix || 'REF').replace(/[^A-Za-z0-9_-]/g, '') || 'REF';
        var start = Math.max(1, parseInt(settings.ref_start, 10) || 1);
        return prefix + '/' + new Date().getFullYear() + '/' + start;
    }

    function masterByName(name) {
        var needle = String(name || '').trim().toLowerCase();
        for (var i = 0; i < state.master.length; i += 1) {
            if (String(state.master[i].name || '').trim().toLowerCase() === needle) {
                return state.master[i];
            }
        }
        return null;
    }

    function newRow(name, rate, durationRequired) {
        return {
            id: state.nextRowId++,
            name: name || '',
            qty: 1,
            duration: durationRequired === false ? 0 : 2,
            rate: Math.max(0, Math.round(Number(rate) || 0))
        };
    }

    function lineTotal(row) {
        var qty = Math.max(0, Number(row.qty) || 0);
        var duration = Math.max(0, Number(row.duration) || 0);
        var rate = Math.max(0, Number(row.rate) || 0);
        // Item tanpa durasi (lisensi/software/token) dihitung qty x rate.
        return Math.round(qty * rate * (duration > 0 ? duration : 1));
    }

    function formatItemDuration(value) {
        return (Number(value) || 0) > 0 ? formatDays(value) : '-';
    }

    function firstUnusedMaster() {
        var used = {};
        state.rows.forEach(function (row) {
            used[String(row.name || '').trim().toLowerCase()] = true;
        });
        for (var i = 0; i < state.master.length; i += 1) {
            var key = String(state.master[i].name || '').trim().toLowerCase();
            if (!used[key]) {
                return state.master[i];
            }
        }
        return state.master[0] || null;
    }

    function computeTotals() {
        var subtotal = 0;
        var mandays = 0;
        var resource = 0;
        var longest = 0;
        var lineItems = [];

        state.rows.forEach(function (row) {
            var qty = Math.max(0, Number(row.qty) || 0);
            var duration = Math.max(0, Number(row.duration) || 0);
            var rate = Math.max(0, Number(row.rate) || 0);
            var hasDuration = duration > 0;
            var itemTotal = Math.round(qty * rate * (hasDuration ? duration : 1));

            lineItems.push({
                name: String(row.name || ''),
                qty: qty,
                duration: duration,
                rate: rate,
                subtotal: itemTotal
            });

            subtotal += itemTotal;
            if (hasDuration) {
                mandays += qty * duration;
                resource += qty;
                longest = Math.max(longest, duration);
            }
        });

        var pct = Math.max(0, Math.min(100, Number(state.discountPct) || 0));
        var discount = Math.round(subtotal * pct / 100);
        var monthDays = Math.max(1, parseInt((state.settings || DEFAULT_SETTINGS).month_days, 10) || 22);

        return {
            lineItems: lineItems,
            subtotal: subtotal,
            discountPct: pct,
            discount: discount,
            grandTotal: subtotal - discount,
            mandays: mandays,
            resource: resource,
            longest: longest,
            month: longest / monthDays
        };
    }

    function getField(id) {
        var element = byId(id);
        return element ? element.value : '';
    }

    function setField(id, value) {
        var element = byId(id);
        if (element) {
            element.value = value;
        }
    }

    function updateSummary() {
        var totals = computeTotals();
        var set = function (id, text) {
            var element = byId(id);
            if (element) {
                element.textContent = text;
            }
        };

        set('sum-mandays', formatDays(totals.mandays));
        set('sum-duration', formatDays(totals.longest) + ' (+' + totals.month.toFixed(1) + ' Month)');
        set('sum-resource', formatDecimal(totals.resource, 2) + ' Manpower');
        set('sum-subtotal', formatRp(totals.subtotal));
        set('sum-discount', '\u2212 ' + formatRp(totals.discount));
        set('sum-discount-label', 'Discount (' + formatDecimal(totals.discountPct, 1) + '%)');
        set('sum-total', formatRp(totals.grandTotal));
    }

